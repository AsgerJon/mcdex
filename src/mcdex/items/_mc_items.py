class MCItems(MCThing, strictCase=False):
  """
  The catalogue of the game's items, each a member. A member is named
  by its unique name in PascalCase, and found by that name in any case or
  by the unique name itself:

    pinkWool = MCItems.PinkWool
    pinkWool is MCItems['pink_wool']  # True
    pinkWool[Version.V1_12_2]  # ItemId('pink_wool', 'minecraft:wool:6')
    len(MCItems)

  Implementation
  --------------

  All of it is 'MCThing's, reading 'items.json' beside this module.
  mcdex's tools write the members, one for every thing of that file.
  """

