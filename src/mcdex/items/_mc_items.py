class MCItems(MCThing):
  """
  The catalogue of the game's items, each a member, found by its name in
  capitals, in any case, or by its unique name:

    pinkWool = MCItems.PINK_WOOL
    pinkWool is MCItems['pink_wool']  # True
    pinkWool['1.12.2']  # ItemId('pink_wool', 'minecraft:wool:6')
    len(MCItems)

  Implementation
  --------------

  All of it is 'MCThing's, reading 'items.json' beside this module.
  mcdex's tools write the members, one for every name of that file.
  """

