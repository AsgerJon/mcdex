  def _record(self, ) -> dict:
    """The item's record, checked for all three of its tables."""
    record = MCThing._record(self)
    for table in ('maxStackSize', 'equipmentSlot'):
      if not record.get(table):
        infoSpec = """%s('%s') received no '%s'"""
        raise ValueError(infoSpec % (type(self).__name__, self.value, table))
    return record

  def _read(self, table: str, record: dict) -> Changes:
    """
    The changes of one of the item's tables: its ids as any thing's, a
    stack size an 'int' from 1 to 99, a slot an 'EquipmentSlot' by the
    name the game serializes it by. The stack sizes and slots must begin
    by the first version that has the item.
    """
    if table == 'ids':
      return MCThing._read(self, table, record)
    if table == 'maxStackSize':
      pairs = []
      for key, size in record[table].items():
        if not isinstance(size, int):
          raise TypeException('maxStackSize', size, int)
        if not 0 < size < 100:
          infoSpec = """%s('%s').maxStackSize must be from 1 to 99, not:
          %d"""
          clsName = type(self).__name__
          raise ValueError(textFmt(infoSpec % (clsName, self.value, size)))
        pairs.append((self._position(Version(key)), size))
    else:
      pairs = [(self._position(Version(key)), EquipmentSlot(slot))
               for key, slot in record[table].items()]
    changes = self._sorted(pairs)
    present = self._present()
    if changes[0][0] > present[0]:
      infoSpec = """%s('%s') has no '%s' for %s"""
      version_ = self._versions()[present[0]]
      info = infoSpec % (type(self).__name__, self.value, table,
                         version_.value)
      raise ValueError(info)
    return changes

  def _present(self, ) -> list[int]:
    """The positions of the versions vanilla has the item in."""
    changes = self._changes('ids')
    first, _ = changes[0]
    return [i for i in range(first, len(self._versions()))
            if self._valueIn(changes, i)]

  def _table(self, table: str) -> dict:
    """
    A table of the item, built at the first call and kept: the ids from
    the first version of the data, the stack sizes and slots for every
    version that has the item.
    """
    if table == 'ids':
      return MCThing._table(self, table)
    key = (type(self).__name__, self.name, table, 'table')
    tables = MCThing.__thing_tables__
    if key not in tables:
      changes = self._changes(table)
      versions = self._versions()
      tables[key] = {versions[i]: self._valueIn(changes, i)
                     for i in self._present()}
    return tables[key]

