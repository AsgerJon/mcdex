  @maxStackSize.GET
  def _getMaxStackSize(self, ) -> StackSizes:
    """The max stack size of every version that has the item, a new dict."""
    return dict(self._table('maxStackSize'))

  @equipmentSlot.GET
  def _getEquipmentSlot(self, ) -> Slots:
    """The equipment slot of every version that has the item, a new dict."""
    return dict(self._table('equipmentSlot'))

